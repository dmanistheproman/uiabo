"""Qualitative, cited web research; separate from quote-validated evidence votes.

Source URLs are assigned from provider citation metadata by the research
transport. Findings are the model's analysis, never copied source quotations.
"""

from datetime import date
import ipaddress
from typing import Literal

from pydantic import AnyHttpUrl, BaseModel, ConfigDict, Field, field_validator, model_validator
from pydantic_core import PydanticCustomError


ResearchVerdict = Literal[
    "true", "likely_true", "mixed", "likely_false", "false",
    "insufficient_evidence", "not_checkable",
]

# outcome, legacy concern label, qualitative evidence strength, public label
VERDICT_PRESENTATION = {
    "true": ("supported", "Low Concern", "Strong", "Strong evidence this is true"),
    "likely_true": ("supported", "Low Concern", "Moderate", "Evidence suggests this is true"),
    "mixed": ("conflicting", "Needs Caution", "Moderate", "Mixed evidence"),
    "likely_false": ("likely_misinformation", "High Concern", "Limited", "Likely misinformation"),
    "false": ("contradicted", "High Concern", "Strong", "Strong evidence this is false"),
    "insufficient_evidence": ("insufficient_evidence", "Not Enough Information", "Insufficient", "Not enough evidence"),
    "not_checkable": ("not_checkable", "Not Enough Information", "Insufficient", "Not a factual claim"),
}


class ResearchSource(BaseModel):
    model_config = ConfigDict(extra="forbid")

    id: str = Field(pattern=r"^c(?:[1-9]|1[0-9]|20)$")
    title: str = Field(min_length=1, max_length=600)
    url: AnyHttpUrl
    publisher: str | None = Field(default=None, min_length=1, max_length=200)

    @field_validator("url")
    @classmethod
    def public_url(cls, value):
        host = value.host or ""
        if value.username or value.password or host.lower() in {"localhost", "localhost.localdomain"} or host.lower().endswith(".localhost"):
            raise ValueError("Research citations require public HTTP URLs without credentials.")
        try:
            address = ipaddress.ip_address(host.strip("[]"))
        except ValueError:
            if "." not in host or host.lower().endswith((".local", ".internal", ".lan")):
                raise ValueError("Research citations require public HTTP URLs.") from None
        else:
            if not address.is_global:
                raise ValueError("Research citations cannot point to private network addresses.")
        return value


class ResearchFinding(BaseModel):
    model_config = ConfigDict(extra="forbid")

    claim: str = Field(min_length=1, max_length=1500, description=(
        "An assertion from the original message assessed in the research report. "
        "Put official baseline facts in the explanation; do not substitute them for the allegation being checked."))
    status: Literal["supported", "contradicted", "mixed", "unresolved"] = Field(description=(
        "The report's finding about this assertion: supported, evidence weighs against it (contradicted), "
        "credible conflict about this same assertion (mixed), or cannot establish it (unresolved). "
        "Do not turn absence of support alone into a contradiction."))
    explanation: str = Field(min_length=1, max_length=3000, description=(
        "Explain the report's evidence and qualifications in plain English, without strengthening its reasoning."))
    source_ids: list[str] = Field(default_factory=list, max_length=20, description=(
        "Only IDs from the supplied native citation list, such as c1. Every non-unresolved finding needs references."))
    material: bool = Field(default=True, description="Whether this assertion is important to the original message's truth.")
    basis: Literal["direct", "bounded_inference", "unresolved"] = Field(default="direct", description=(
        "Use unresolved whenever status is unresolved. Use direct for directly applicable evidence, "
        "or bounded_inference only for a qualified inference actually made in the research report. State its limitations."))

    @model_validator(mode="after")
    def validate_basis(self):
        if len(self.source_ids) != len(set(self.source_ids)):
            raise PydanticCustomError("research_duplicate_references", "A research finding cannot repeat citation IDs.")
        if self.status != "unresolved" and (not self.source_ids or self.basis == "unresolved"):
            raise PydanticCustomError("research_finding_references_required", "A decisive research finding requires citations and an explicit reasoning basis.")
        if self.status == "unresolved" and self.basis != "unresolved":
            raise PydanticCustomError("research_unresolved_basis", "An unresolved research finding must identify its unresolved basis.")
        return self


class ResearchDraft(BaseModel):
    """Only this payload is generated by the report-formatting call."""
    model_config = ConfigDict(extra="forbid")

    verdict: ResearchVerdict = Field(description=(
        "Preserve the report's verdict. A misinformation verdict needs a material finding weighed against by "
        "the evidence; true needs direct support for every material finding; mixed needs conflict about the same assertion."))
    summary: str = Field(min_length=1, max_length=4000, description="A concise explanation preserving the researched conclusion and its qualifications.")
    findings: list[ResearchFinding] = Field(default_factory=list, max_length=8, description=(
        "Assess the original material assertions individually. Supported background facts do not replace unresolved or contradicted allegations."))
    limitations: list[str] = Field(default_factory=list, max_length=8, description=(
        "The report's remaining uncertainty and limitations; required for any bounded inference. Each entry is 1 to 1000 characters."))
    recommended_action: str = Field(min_length=1, max_length=1000)

    @field_validator("limitations")
    @classmethod
    def bounded_limits(cls, values):
        if any(not value.strip() or len(value) > 1000 for value in values):
            raise PydanticCustomError("research_limitations_invalid", "Research limitations must contain 1 to 1000 characters.")
        return values

    @model_validator(mode="after")
    def verdict_matches_findings(self):
        material = [finding for finding in self.findings if finding.material]
        if self.verdict == "not_checkable":
            if any(finding.status != "unresolved" for finding in self.findings):
                raise PydanticCustomError("research_nonfactual_findings", "Non-factual research cannot contain decisive factual findings.")
            return self
        if not material:
            raise PydanticCustomError("research_material_findings_required", "A factual research assessment needs a material finding.")
        if any(finding.basis == "bounded_inference" for finding in self.findings) and not self.limitations:
            raise PydanticCustomError("research_inference_limitations_required", "A bounded research inference must state its limitations.")
        if self.verdict in {"true", "likely_true"}:
            if any(finding.status != "supported" for finding in material):
                raise PydanticCustomError("research_support_incomplete", "A supported overall verdict requires support for every material finding.")
            if self.verdict == "true" and any(finding.basis != "direct" for finding in material):
                raise PydanticCustomError("research_direct_support_required", "Strong support requires direct evidence for the material findings.")
        elif self.verdict in {"false", "likely_false"}:
            contradictions = [finding for finding in material if finding.status == "contradicted"]
            if not contradictions:
                raise PydanticCustomError("research_contradiction_required", "A misinformation verdict requires evidence against a material finding.")
            if self.verdict == "false" and not any(finding.basis == "direct" for finding in contradictions):
                raise PydanticCustomError("research_direct_contradiction_required", "Strong contradiction requires a direct material contradiction.")
        elif self.verdict == "mixed":
            if not any(finding.status == "mixed" for finding in material):
                raise PydanticCustomError("research_mixed_conflict_required", "Mixed research requires conflicting evidence about the same material assertion; separate true and false components do not cancel each other.")
        elif self.verdict == "insufficient_evidence":
            if any(finding.status == "contradicted" for finding in material):
                raise PydanticCustomError("research_unresolved_cannot_erase_contradiction", "An unresolved component cannot erase a contradicted material finding.")
            if not any(finding.status == "unresolved" for finding in material):
                raise PydanticCustomError("research_unresolved_required", "Insufficient research requires an unresolved material finding.")
        return self


class ResearchAssessment(ResearchDraft):
    """Stored research assessment with server-bound citation metadata."""

    version: Literal["openai-web-v1"] = "openai-web-v1"
    sources: list[ResearchSource] = Field(default_factory=list, max_length=20)
    as_of: date
    provider: Literal["openai"] = "openai"
    model: str = Field(min_length=1, max_length=100)
    research_text: str | None = Field(default=None, max_length=50000)

    @model_validator(mode="after")
    def bind_source_ids(self):
        source_ids = [source.id for source in self.sources]
        if len(source_ids) != len(set(source_ids)):
            raise PydanticCustomError("research_duplicate_source_ids", "Research source IDs must be unique.")
        if len({str(source.url) for source in self.sources}) != len(self.sources):
            raise PydanticCustomError("research_duplicate_source_urls", "Research source URLs must be unique.")
        known = set(source_ids)
        if any(set(finding.source_ids) - known for finding in self.findings):
            raise PydanticCustomError("research_unknown_source_ids", "Research findings must cite server-bound sources.")
        if self.verdict not in {"insufficient_evidence", "not_checkable"} and not self.sources:
            raise PydanticCustomError("research_verdict_sources_required", "A decisive research verdict requires cited sources.")
        return self
